"""HTML linter for interactive figures.

Evaluates interactive explainers and figures generated by techfig using Playwright.
Checks for:
1. Populated readout and value elements (.tf-value, .tf-readout).
2. Inert controls (range sliders that produce < 0.001 pixel diff between min and max).
3. Text collisions across slider states ('min', 'mid', 'max') using SVG bounding boxes.
4. Console / JavaScript errors during page lifecycle.
"""
import functools
import http.server
import io
from pathlib import Path
import socketserver
import threading
from typing import Any, Dict, List, Sequence, Tuple


class _EphemeralServer:
    """Ephemeral HTTP server serving a directory on an arbitrary port."""

    def __init__(self, directory: Path):
        self.directory = directory
        handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(directory))
        self.httpd = socketserver.TCPServer(("127.0.0.1", 0), handler)
        self.port = self.httpd.server_address[1]
        self.thread = threading.Thread(target=self.httpd.serve_forever, daemon=True)
        self.thread.start()

    def stop(self) -> None:
        try:
            self.httpd.shutdown()
            self.httpd.server_close()
        except Exception:
            pass


def compute_pixel_diff(img1_bytes: bytes, img2_bytes: bytes) -> Tuple[float, bool]:
    """Compute the fraction of differing pixels between two PNG images.

    Returns:
        (diff_fraction, used_pil)
    """
    try:
        from PIL import Image, ImageChops

        im1 = Image.open(io.BytesIO(img1_bytes)).convert("RGBA")
        im2 = Image.open(io.BytesIO(img2_bytes)).convert("RGBA")
        if im1.size != im2.size:
            return 1.0, True
        total = im1.width * im1.height
        if total == 0:
            return 0.0, True
        diff = ImageChops.difference(im1, im2)
        diff_gray = diff.convert("L")
        hist = diff_gray.histogram()
        diff_count = sum(hist[1:])
        return diff_count / total, True
    except ImportError:
        # Fallback to binary PNG comparison if PIL is not installed
        fraction = 0.0 if img1_bytes == img2_bytes else 1.0
        return fraction, False


def lint_html(
    path: str | Path,
    states: Sequence[str] = ("min", "mid", "max"),
    _force_http_server: bool = False,
) -> Dict[str, Any]:
    """Lint an interactive HTML page with Playwright.

    Args:
        path: Path to the HTML file to inspect.
        states: Sequence of slider states to evaluate for text collisions.
        _force_http_server: Force using local ephemeral HTTP server instead of file://.

    Returns:
        Dict with report results: score, issues, inert_controls, text_overlaps, js_errors.
        If Playwright is unavailable, returns {ok: None, skipped: 'playwright unavailable'}.
    """
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        return {"ok": None, "skipped": "playwright unavailable"}

    abs_path = Path(path).resolve()
    if not abs_path.exists():
        raise FileNotFoundError(f"HTML file not found: {path}")

    issues: List[str] = []
    inert_controls: List[str] = []
    text_overlaps: Dict[str, List[List[str]]] = {}
    js_errors: List[str] = []

    server: _EphemeralServer | None = None
    try:
        with sync_playwright() as pw:
            try:
                browser = pw.chromium.launch()
            except Exception as exc:
                return {"ok": None, "skipped": f"playwright unavailable: {exc}"}

            try:
                page = browser.new_page()

                # Register console and page error listeners
                page.on("pageerror", lambda exc: js_errors.append(str(exc)))
                page.on(
                    "console",
                    lambda msg: js_errors.append(msg.text) if msg.type == "error" else None,
                )

                # Attempt loading via file:// unless ephemeral server is forced
                loaded = False
                if not _force_http_server:
                    try:
                        file_uri = abs_path.as_uri()
                        resp = page.goto(file_uri, wait_until="load", timeout=10000)
                        if resp is not None and resp.status >= 400:
                            raise RuntimeError(f"HTTP error {resp.status}")
                        loaded = True
                    except Exception:
                        loaded = False

                if not loaded:
                    server = _EphemeralServer(abs_path.parent)
                    http_url = f"http://127.0.0.1:{server.port}/{abs_path.name}"
                    page.goto(http_url, wait_until="load", timeout=10000)

                # Wait for initial frame render
                page.evaluate("() => new Promise(requestAnimationFrame)")

                # -------------------------------------------------------------
                # Check 1: Populated .tf-value and .tf-readout elements at load
                # -------------------------------------------------------------
                bad_readouts = page.evaluate("""() => {
                    const results = [];
                    const els = Array.from(document.querySelectorAll('.tf-value, .tf-readout'));
                    for (const el of els) {
                        const txt = (el.textContent || '').trim();
                        const ident = el.id || el.getAttribute('data-name') || el.className;
                        const invalid = ['', '-', '\u2013', '\u2014', 'NaN', 'undefined', 'null'];
                        if (invalid.includes(txt) || txt.includes('NaN') || txt.includes('undefined')) {
                            results.push({id: ident, text: txt});
                        }
                    }
                    return results;
                }""")
                for item in bad_readouts:
                    issues.append(
                        f"Unpopulated or invalid readout/value '{item['id']}': text is '{item['text']}'"
                    )

                # -------------------------------------------------------------
                # Check 2: Range inputs for inert controls
                # -------------------------------------------------------------
                controls_info = page.evaluate("""() => {
                    const inputs = Array.from(document.querySelectorAll('input[type="range"]'));
                    return inputs.map((inp, idx) => ({
                        index: idx,
                        name: inp.getAttribute('data-name') || inp.id || inp.name || `slider_${idx}`,
                        min: inp.min !== '' ? parseFloat(inp.min) : 0,
                        max: inp.max !== '' ? parseFloat(inp.max) : 100,
                        val: inp.value !== '' ? parseFloat(inp.value) : 0,
                        dataFig: inp.getAttribute('data-fig') || '',
                    }));
                }""")

                used_pil = True
                for ctrl in controls_info:
                    idx = ctrl["index"]
                    name = ctrl["name"]
                    min_v = ctrl["min"]
                    max_v = ctrl["max"]
                    orig_v = ctrl["val"]

                    def set_slider(val: float) -> None:
                        page.evaluate(f"""() => {{
                            const inps = document.querySelectorAll('input[type="range"]');
                            const inp = inps[{idx}];
                            if (inp) {{
                                inp.value = "{val}";
                                inp.dispatchEvent(new Event('input', {{bubbles: true}}));
                                inp.dispatchEvent(new Event('change', {{bubbles: true}}));
                            }}
                            if (window.__tf && window.__tf.update) {{
                                window.__tf.update();
                            }}
                        }}""")
                        page.evaluate("() => new Promise(requestAnimationFrame)")

                    # Locate figure element (excluding controls if wrapped inside)
                    fig_el = None
                    if ctrl.get("dataFig"):
                        fig_id = ctrl["dataFig"]
                        fig_el = (
                            page.query_selector(f"figure#{fig_id}")
                            or page.query_selector(f"#{fig_id}")
                            or page.query_selector(f"figure[data-fig='{fig_id}']")
                        )
                    if fig_el is None:
                        fig_el = page.query_selector("figure")
                    if fig_el is None:
                        fig_el = page.query_selector("svg")

                    # If figure element contains .tf-controls, clip to child svg
                    if fig_el is not None and fig_el.query_selector(".tf-controls") is not None:
                        svg_child = fig_el.query_selector("svg")
                        if svg_child is not None:
                            fig_el = svg_child

                    # Set to min and screenshot
                    set_slider(min_v)
                    img_min = fig_el.screenshot() if fig_el else page.screenshot()

                    # Set to max and screenshot
                    set_slider(max_v)
                    img_max = fig_el.screenshot() if fig_el else page.screenshot()

                    # Compute pixel diff
                    diff_fraction, pil_ok = compute_pixel_diff(img_min, img_max)
                    if not pil_ok:
                        used_pil = False

                    if diff_fraction < 0.001:
                        inert_controls.append(name)
                        issues.append(
                            f"Inert control: '{name}' does not affect figure (pixel diff {diff_fraction:.5f} < 0.001)"
                        )

                    # Restore original slider value
                    set_slider(orig_v)

                if not used_pil:
                    issues.append("Note: PIL unavailable, fell back to byte comparison for pixel diffing")

                # -------------------------------------------------------------
                # Check 3: Text overlaps across states
                # -------------------------------------------------------------
                for st in states:
                    # Set all sliders to state simultaneously
                    page.evaluate(f"""() => {{
                        const state = "{st}";
                        const inps = document.querySelectorAll('input[type="range"]');
                        for (const inp of inps) {{
                            const min = inp.min !== '' ? parseFloat(inp.min) : 0;
                            const max = inp.max !== '' ? parseFloat(inp.max) : 100;
                            let val = (min + max) / 2;
                            if (state === 'min') {{
                                val = min;
                            }} else if (state === 'max') {{
                                val = max;
                            }} else if (state === 'mid') {{
                                val = (min + max) / 2;
                            }}
                            inp.value = val;
                            inp.dispatchEvent(new Event('input', {{bubbles: true}}));
                            inp.dispatchEvent(new Event('change', {{bubbles: true}}));
                        }}
                        if (window.__tf && window.__tf.update) {{
                            window.__tf.update();
                        }}
                    }}""")
                    page.evaluate("() => new Promise(requestAnimationFrame)")

                    pairs = page.evaluate("""() => {
                        function getBox(el) {
                            const bbox = el.getBBox();
                            const svg = el.ownerSVGElement || el;
                            let matrix = null;
                            try {
                                if (svg && svg.getScreenCTM && el.getScreenCTM) {
                                    const sScreen = svg.getScreenCTM();
                                    const eScreen = el.getScreenCTM();
                                    if (sScreen && eScreen) {
                                        matrix = sScreen.inverse().multiply(eScreen);
                                    }
                                }
                            } catch (e) {
                                matrix = null;
                            }
                            if (!matrix || !svg || !svg.createSVGPoint) {
                                return {x: bbox.x, y: bbox.y, width: bbox.width, height: bbox.height};
                            }
                            const pt1 = svg.createSVGPoint(); pt1.x = bbox.x; pt1.y = bbox.y;
                            const pt2 = svg.createSVGPoint(); pt2.x = bbox.x + bbox.width; pt2.y = bbox.y;
                            const pt3 = svg.createSVGPoint(); pt3.x = bbox.x + bbox.width; pt3.y = bbox.y + bbox.height;
                            const pt4 = svg.createSVGPoint(); pt4.x = bbox.x; pt4.y = bbox.y + bbox.height;
                            
                            const t1 = pt1.matrixTransform(matrix);
                            const t2 = pt2.matrixTransform(matrix);
                            const t3 = pt3.matrixTransform(matrix);
                            const t4 = pt4.matrixTransform(matrix);
                            
                            const minX = Math.min(t1.x, t2.x, t3.x, t4.x);
                            const maxX = Math.max(t1.x, t2.x, t3.x, t4.x);
                            const minY = Math.min(t1.y, t2.y, t3.y, t4.y);
                            const maxY = Math.max(t1.y, t2.y, t3.y, t4.y);
                            return {x: minX, y: minY, width: maxX - minX, height: maxY - minY};
                        }

                        const textEls = Array.from(document.querySelectorAll('text')).filter(t => {
                            if (t.style && t.style.display === 'none') return false;
                            const p = t.parentElement;
                            if (p && p.style && p.style.display === 'none') return false;
                            const txt = (t.textContent || '').trim();
                            return txt.length > 0;
                        });

                        const items = textEls.map(t => {
                            let ident = t.getAttribute('id');
                            if (!ident && t.parentElement && t.parentElement.getAttribute('id')) {
                                ident = t.parentElement.getAttribute('id');
                            }
                            if (!ident) {
                                ident = (t.textContent || '').trim();
                            }
                            let box = {x: 0, y: 0, width: 0, height: 0};
                            try {
                                box = getBox(t);
                            } catch (e) {}
                            return {id: ident, box: box, el: t};
                        });

                        const overlappingPairs = [];
                        for (let i = 0; i < items.length; i++) {
                            for (let j = i + 1; j < items.length; j++) {
                                const b1 = items[i].box;
                                const b2 = items[j].box;
                                const xOverlap = Math.max(0, Math.min(b1.x + b1.width, b2.x + b2.width) - Math.max(b1.x, b2.x));
                                const yOverlap = Math.max(0, Math.min(b1.y + b1.height, b2.y + b2.height) - Math.max(b1.y, b2.y));
                                const area = xOverlap * yOverlap;
                                if (area > 4) {
                                    overlappingPairs.push([items[i].id, items[j].id]);
                                }
                            }
                        }
                        return overlappingPairs;
                    }""")
                    text_overlaps[st] = pairs
                    for p in pairs:
                        issues.append(f"Text overlap at state '{st}': '{p[0]}' and '{p[1]}'")

                # -------------------------------------------------------------
                # Check 4: JavaScript / console errors
                # -------------------------------------------------------------
                for err in js_errors:
                    issues.append(f"Console/JS error: {err}")

            finally:
                browser.close()
    finally:
        if server is not None:
            server.stop()

    # Calculate overall quality score:
    # Score = 1 - 0.3*(inert>0) - min(0.5, 0.1*n_overlap_pairs) - 0.2*(js_errors>0), clamped [0, 1]
    unique_overlap_pairs = {
        tuple(sorted([str(p[0]), str(p[1])]))
        for pairs in text_overlaps.values()
        for p in pairs
    }
    n_overlap_pairs = len(unique_overlap_pairs)

    inert_penalty = 0.3 if len(inert_controls) > 0 else 0.0
    overlap_penalty = min(0.5, 0.1 * n_overlap_pairs)
    js_penalty = 0.2 if len(js_errors) > 0 else 0.0

    raw_score = 1.0 - inert_penalty - overlap_penalty - js_penalty
    score = max(0.0, min(1.0, round(raw_score, 4)))

    return {
        "ok": True,
        "score": score,
        "issues": issues,
        "inert_controls": inert_controls,
        "text_overlaps": text_overlaps,
        "js_errors": js_errors,
    }
